def mix(c, t, k):
    return tuple(int(c[i] + (t[i] - c[i]) * k) for i in range(3))


def icon(kind, typ, glyph):
    base = TYPE.get(typ, (160, 160, 160))
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    dark = mix(base, (20, 16, 32), 0.55)
    light = mix(base, (255, 255, 255), 0.75)
    for y in range(16):
        for x in range(16):
            d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
            if d > 7.6:
                continue
            if d > 6.6:
                # rim: actives bright, passives dark
                px[x, y] = (*((255, 255, 255) if kind == "a" else (40, 32, 60)), 255)
            elif d > 5.8 and kind == "p":
                px[x, y] = (*mix(base, (40, 32, 60), 0.5), 255)
            else:
                shade = 1 - 0.18 * (y / 15)
                c = tuple(int(v * shade) for v in base)
                if kind == "p":
                    c = mix(c, (30, 26, 50), 0.25)
                px[x, y] = (*c, 255)
    rows = G[glyph]
    on = lambda gx, gy: 0 <= gy < len(rows) and 0 <= gx < len(rows[gy]) and rows[gy][gx] != "."
    for gy, row in enumerate(rows):
        for gx, ch in enumerate(row):
            if ch == ".":
                # soft shadow below-right of the glyph
                if on(gx - 1, gy - 1) and px[gx + 2, gy + 2][3]:
                    px[gx + 2, gy + 2] = (*dark, 255)
                continue
            col = (250, 250, 250) if ch == "#" else light if ch == "+" else dark
            px[gx + 2, gy + 2] = (*col, 255)
    return img


def skills():
    # ask node for the skill table so this stays in sync with config.js
    js = "import('./js/config.js').then(c => console.log(JSON.stringify(Object.fromEntries(Object.entries(c.SKILLS).map(([k, s]) => [k, [s.kind, s.type, s.glyph]])))))"
    out = subprocess.check_output(["node", "-e", js], cwd=ROOT)
    return json.loads(out)


def main():
    os.makedirs(OUT, exist_ok=True)
    sk = skills()
    for k, (kind, typ, glyph) in sk.items():
        if glyph not in G:
            raise SystemExit(f"missing glyph {glyph} for {k}")
        icon(kind, typ, glyph).save(os.path.join(OUT, k + ".png"))
    # contact sheet for review
    n = len(sk)
    cols = 12
    sheet = Image.new("RGBA", (cols * 20 * 4, ((n + cols - 1) // cols) * 20 * 4), (60, 52, 90, 255))
    for i, k in enumerate(sk):
        im = Image.open(os.path.join(OUT, k + ".png")).resize((64, 64), Image.NEAREST)
        sheet.paste(im, ((i % cols) * 80 + 8, (i // cols) * 80 + 8), im)
    sheet.save(os.path.join(os.environ.get("SHEET_DIR", "/tmp"), "skill_icons.png"))
    print(f"{n} skill icons")


if __name__ == "__main__":
    main()
