def build(S):
    """Forms built on top of other sprites (Machop fighter, Megas)."""
    out = {"machopf": list(S["machop"])}
    G = {**S, **SPRITES}
    out["megagengar"] = place(G["gengar"], 24, 18, 3, 4, overlays=[
        # more spikes, a third eye on the forehead and a dark shadow pool
        (3, 0, ["..#...#...#...#..", ".###.###.###.###.", "..#############.."]),
        (12, 4, ["&&"]),
        (0, 15, ["....@@@@@@@@@@@@@@@@...", "..@@@@@@@@@@@@@@@@@@@@.", "...@@@@@@@@@@@@@@@@@..."]),
        (0, 9, ["##", "#.", "#."]),
    ])
    out["megaalakazam"] = place(G["alakazam"], 26, 21, 3, 4, overlays=[
        # long beard, red gem, and spoons floating around
        (6, 11, ["<<<<<<<<<", ".<<<<<<<.", "..<<<<<..", "...<<<..."]),
        (10, 4, ["II"]),
        (0, 1, [".>", ">.", "-."]),
        (22, 0, [">.", ".>", ".-"]),
        (24, 9, [">", ">", "-"]),
        (0, 12, [">", ">", "-"]),
        (11, 0, [">>", ".-"]),
    ])
    out["megamewtwox"] = place(G["mewtwo"], 26, 23, 1, 2, overlays=[
        # bulkier shoulders and a blue tail, a tube from the back of the head
        (6, 7, ["XX", "XX"]),
        (16, 7, ["XX", "XX"]),
        (5, 0, [".KKK.", "K...K", "....K"]),
        (8, 12, ["KKKKK", "KKKKKKK", "KKKKKKK", ".KKKK"]),
        (16, 14, ["....KK", "...KKK", "..KKK.", ".KKK..", "KKK..."]),
    ])
    out["megamewtwoy"] = place(G["mewtwo"], 26, 23, 3, 2, overlays=[
        # a long flowing tail from the back of its head and a slimmer frame
        (0, 1, ["....0000000", "..00000....", ".000.......", "000........", "00........."]),
        (10, 13, ["0000", "0000"]),
    ], erase=[(12, 0, 3, 2)])
    return out
