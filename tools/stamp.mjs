// Cache-busting: stamps index.html with a version hash of the code so browsers always load fresh files
// after an update. An import map gives every module a ?v=<hash> URL (static imports between modules
// go through it too). Run after changing anything in js/ or css/:   node tools/stamp.mjs
// `node tools/stamp.mjs --check` exits with an error if the stamp is out of date (used by npm test).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = [...readdirSync(join(root, 'js')).filter((f) => f.endsWith('.js')).sort().map((f) => 'js/' + f), 'css/style.css'];
const hash = createHash('sha1');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const v = hash.digest('hex').slice(0, 10);

const map = { imports: Object.fromEntries(files.filter((f) => f.endsWith('.js')).map((f) => ['./' + f, `./${f}?v=${v}`])) };
const block = `<!-- stamp:start (generated by tools/stamp.mjs) -->
  <script type="importmap">${JSON.stringify(map)}</script>
  <link rel="stylesheet" href="css/style.css?v=${v}">
  <!-- stamp:end -->`;

const path = join(root, 'index.html');
const html = readFileSync(path, 'utf8');
let out = html.replace(/<!-- stamp:start[\s\S]*?<!-- stamp:end -->/, block);
if (out === html && !html.includes('stamp:start')) out = html.replace('<link rel="stylesheet" href="css/style.css">', block);
out = out.replace(/<script type="module" src="js\/main\.js[^"]*"><\/script>/, `<script type="module" src="js/main.js?v=${v}"></script>`);

if (process.argv.includes('--check')) {
  if (out !== html) { console.error('index.html is not stamped for the current code: run node tools/stamp.mjs'); process.exit(1); }
  console.log('stamp up to date', v);
} else {
  writeFileSync(path, out);
  console.log('stamped', v);
}
